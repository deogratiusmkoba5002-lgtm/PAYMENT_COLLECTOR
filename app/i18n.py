def get_locale():
    return session.get("lang", "en")


def t(key, **kwargs):
    lang = get_locale()
    text = TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(
        key, TRANSLATIONS["en"].get(key, key)
    )
    if kwargs:
        text = text.format(**kwargs)
    return text